// RN-007 — pipeline de conteúdo (docs-as-code, RN-008 strict).
//
// Ingestão: `docs-content/**.md` do próprio repo (fonte EN — RN-013).
// A fonte do KIT (repo Golmet/golmet-cli — FORMATO.md + docs/) ativa quando
// o repo abrir (CR-002/RN-007-8/9 — config comentada em SOURCES).
//
// Gera:
//   src/app/docs/docs-content.generated.ts  — páginas + TOC (para prerender)
//   public/docs-search.json                 — corpo para a busca client-side (RN-009)
//
// Strict (RN-008/ADR-005): qualquer violação = exit 1, nada publica.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { Marked } from 'marked';

const SOURCES = [
  // CR-002/RN-007-8/9 — ativa quando o repo do kit abrir (clone shallow da main):
  // { type: 'git', repo: 'https://github.com/Golmet/golmet-cli', branch: 'main',
  //   paths: ['FORMATO.md', 'docs'], prefix: 'kit' },
  { type: 'local', dir: 'docs-content', group: 'Documentation', lang: 'en', exclude: ['cli'] },
  // RN-007-8/9 — docs do release publicado (READMEs extraídos do tarball npm
  // por tools/fetch-cli-docs.mjs). A variante PT-BR (README.pt-br.md) recebe
  // lang próprio — ADR-009: fonte EN, PT-BR derivado do próprio kit.
  { type: 'local', dir: 'docs-content/cli', group: 'CLI release', lang: 'en' },
];

const OUT_TS = 'src/app/docs/docs-content.generated.ts';
const OUT_SEARCH = 'public/docs-search.json';

const marked = new Marked();

const slugOf = (rel) =>
  rel
    .replace(/\.md$/i, '')
    .replace(/\\/g, '/')
    .toLowerCase();

const titleOf = (md, rel) => {
  const h1 = md.match(/^#\s+(.+)$/m);
  if (h1) return h1[1].trim();
  return rel
    .split(/[\\/]/)
    .pop()
    .replace(/\.md$/i, '')
    .replace(/[-_]/g, ' ');
};

/** RN-008 — validação strict de uma página do portal. Devolve falhas. */
export function validatePage(md, rel) {
  const errors = [];
  // H1s contam FORA de blocos de código — `# comentário` em fence shell do
  // README do kit não é heading (docs reais do release, RN-007-8).
  const mdNoFences = md.replace(/```[\s\S]*?```/g, ' ');
  const h1s = mdNoFences.match(/^#\s+.+$/gm) ?? [];
  if (h1s.length !== 1) errors.push(`${rel}: exatamente 1 H1 é obrigatório (achados: ${h1s.length})`);
  if (md.trim().length < 40) errors.push(`${rel}: corpo vazio ou mínimo demais`);
  if (md.trimStart().startsWith('---')) {
    const closed = md.trimStart().split('\n').slice(1).includes('---');
    if (!closed) errors.push(`${rel}: front matter aberto (--- sem fechar)`);
  }
  return errors;
}

function stripMd(md) {
  return md
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/[#*`>\[\]()!]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function walkMd(dir, exclude = []) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (exclude.includes(entry.name)) continue;
      out.push(...walkMd(full, exclude));
    } else if (entry.name.toLowerCase().endsWith('.md')) out.push(full);
  }
  return out;
}

function ingest() {
  const pages = [];
  const failures = [];
  for (const source of SOURCES) {
    if (source.type !== 'local') continue;
    for (const file of walkMd(source.dir, source.exclude ?? [])) {
      const rel = relative(source.dir, file).replace(/\\/g, '/');
      const md = readFileSync(file, 'utf8');
      failures.push(...validatePage(md, rel));
      const slug = slugOf(rel);
      // Variante PT-BR do release (.pt-br.md) — ADR-009/RN-011.
      const lang = rel.toLowerCase().endsWith('.pt-br.md') ? 'pt-br' : source.lang;
      const html = marked.parse(md);
      pages.push({
        slug,
        title: titleOf(md, rel),
        html,
        lang,
        group: source.group,
        text: stripMd(md),
      });
    }
  }
  return { pages: pages.sort((a, b) => a.slug.localeCompare(b.slug)), failures };
}

function emitGenerated(pages) {
  const groups = new Map();
  for (const page of pages) {
    if (!groups.has(page.group)) groups.set(page.group, []);
    groups.get(page.group).push({ slug: page.slug, title: page.title });
  }
  const toc = Array.from(groups, ([group, items]) => ({ group, items }));

  const ts = `// GENERATED by tools/build-docs.mjs (RN-007 pipeline) — do not edit by hand.
// Regenerated on every build; the truth is the .md in docs-content/ (RN-008).
// text vai apenas para public/docs-search.json (busca client-side — RN-009).
export interface GeneratedDocPage {
  slug: string;
  title: string;
  html: string;
  lang: string;
  group: string;
}
export interface GeneratedTocGroup {
  group: string;
  items: readonly { slug: string; title: string }[];
}
export const GENERATED_DOCS: readonly GeneratedDocPage[] = ${JSON.stringify(
    pages.map(({ slug, title, html, lang, group }) => ({ slug, title, html, lang, group })),
    null,
    2,
  )};
export const GENERATED_TOC: readonly GeneratedTocGroup[] = ${JSON.stringify(toc, null, 2)};
`;
  writeFileSync(OUT_TS, ts);
  writeFileSync(
    OUT_SEARCH,
    JSON.stringify(pages.map(({ slug, title, text }) => ({ slug, title, text })), null, 2),
  );
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].replace(/\\/g, '/').split('/').pop());
if (isMain) {
  const { pages, failures } = ingest();
  if (failures.length > 0) {
    console.error(`build-docs: ${failures.length} violação(ões) strict:`);
    for (const failure of failures) console.error(`  ✗ ${failure}`);
    process.exit(1);
  }
  emitGenerated(pages);
  console.log(`build-docs: ${pages.length} página(s) gerada(s) — strict ok.`);
}
